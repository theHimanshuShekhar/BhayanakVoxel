//! The ground near a character: the level 0 bricks it can touch, held so that a collision query
//! reads them and never generates one.
//!
//! The client's predictor and the server each keep a [`Ground`] per character, generated from the
//! Planet's seed ([`BrickSource`]). Generation is deterministic, so both hold the same bricks.
//! Where an Edit has changed one, the store holds the changed brick instead, and [`Footing`] reads
//! that first.
//!
//! # The window
//!
//! The bricks live in a ring buffer of [`SIDE`] bricks a side: a brick is in the slot of its
//! coordinate modulo [`SIDE`], and is held while no brick of another coordinate has taken the
//! slot. So the ground behind a character is evicted by the ground ahead of it, with nothing to
//! track, and the memory is the same however far it walks (see [`Ground::MAX_BYTES`]). A brick is a
//! function of its coordinate, so a slot that holds the coordinate asked for holds the right brick,
//! however old.
//!
//! # Filling it
//!
//! The ground fills a ball of [`REACH`] Voxels around a centre brick, nearest brick first, at most
//! [`Ground::rate`] new bricks per [`Ground::fill`]: the caller says when, which is once per input
//! on the server (so what is ready is a function of the inputs, whatever the clock) and once per
//! tick on the client, and the cost of a tick stays bounded. The centre follows the character, but
//! only once the ball is complete, and only when the character is [`RECENTRE`] bricks from it: a
//! character that outruns the generator waits at the edge of the ball, and a ball that is moved
//! mostly holds the bricks it needs already.
//!
//! The order is what makes the ball's *ready radius* simple: every brick that a ball of that radius
//! touches comes before the first brick that is missing. [`Ground::ready`] is that ball, as the
//! [`Leash`] the server may hold the character to.

use std::mem::size_of;
use std::sync::{Arc, OnceLock};

use brick_store::{BRICK_SIZE, Brick, BrickCoord, BrickSource, BrickStore, VoxelCoord};
use net::Leash;

use crate::{Cell, Occupancy};

/// The farthest a leash reaches from its centre, in Voxels: 8 m. Bigger than a character needs to
/// stand in (2 m), so that it keeps going while the next ground is made.
pub const REACH: i32 = 80;
/// Bricks along a side of the ring buffer: a ball of [`REACH`] is 21 across, and the rest is room
/// for the centre to move, and for a leash to trail it, without the two overwriting each other.
const SIDE: usize = 32;
const SLOTS: usize = SIDE * SIDE * SIDE;
/// Bricks the character may be from the centre of the ball before it is moved.
const RECENTRE: u32 = 3;
/// New bricks generated by one [`Ground::fill`], at the most. Running at 7 m/s on the Planet needs
/// 54 a tick in the mean, in bursts of the most there are while the ball is moved a few bricks;
/// at 64 it did not keep up, once in a kilometre. Measured over a kilometre of that, a tick of the
/// server or the client costs 2.2 ms in the mean, 4.5 ms at the 99th percentile and 6.5 ms at the
/// worst, of the 16.7 ms there is: the bricks, at 15 µs each in the mean, are about 0.8 ms of it.
const RATE: usize = 128;
/// What a mixed brick takes besides its palette and its Voxels' indices: its occupancy mask, the
/// two vectors' headers and the rest of its fields.
const MIXED_HEADER: usize = 64 + 24 + 24 + 8;

type Slot = Option<(BrickCoord, Brick)>;

/// A brick of the ball around a centre brick, by where it is from it.
struct Offset {
    /// The square of the distance, in Voxels, from the middle of the centre brick to the nearest
    /// point of this brick.
    gap2: u32,
    brick: [i8; 3],
}

/// The bricks that a ball of [`REACH`] touches, nearest first, ties in coordinate order: the
/// order that every ground fills in.
fn offsets() -> &'static [Offset] {
    static OFFSETS: OnceLock<Vec<Offset>> = OnceLock::new();
    OFFSETS.get_or_init(|| {
        let bricks = REACH / BRICK_SIZE + 1;
        // From the middle of the centre brick (4 Voxels in) to a brick `d` away: the nearest face.
        let gap = |d: i32| {
            if d == 0 {
                0
            } else {
                BRICK_SIZE * d.abs() - BRICK_SIZE / 2
            }
        };
        let mut found = Vec::new();
        for x in -bricks..=bricks {
            for y in -bricks..=bricks {
                for z in -bricks..=bricks {
                    let gap2 = gap(x) * gap(x) + gap(y) * gap(y) + gap(z) * gap(z);
                    if gap2 <= REACH * REACH {
                        found.push(Offset {
                            gap2: gap2 as u32,
                            brick: [x as i8, y as i8, z as i8],
                        });
                    }
                }
            }
        }
        found.sort_by_key(|o| (o.gap2, o.brick));
        found
    })
}

/// The brick `offset` away from `centre`.
fn beside(centre: BrickCoord, offset: &Offset) -> BrickCoord {
    BrickCoord(std::array::from_fn(|a| {
        centre.0[a].saturating_add(i32::from(offset.brick[a]))
    }))
}

/// The brick that `point`, in Voxels, is in.
fn brick_of(point: [f64; 3]) -> BrickCoord {
    VoxelCoord(point.map(|c| c.floor() as i32)).brick()
}

/// The middle of a brick, in Voxels.
fn middle(brick: BrickCoord) -> [f64; 3] {
    brick
        .origin()
        .0
        .map(|o| f64::from(o) + f64::from(BRICK_SIZE) / 2.0)
}

fn slot_of(brick: BrickCoord) -> usize {
    let [x, y, z] = brick.0.map(|c| c.rem_euclid(SIDE as i32) as usize);
    x + y * SIDE + z * SIDE * SIDE
}

pub struct Ground {
    /// Where bricks come from. A Planet with no source is air where nothing is held.
    source: Option<Arc<dyn BrickSource>>,
    slots: Vec<Slot>,
    /// The brick the ball is around, once there is one.
    centre: Option<BrickCoord>,
    /// How many of [`offsets`] are held around the centre: all those before this one.
    next: usize,
    rate: usize,
}

impl Ground {
    /// The most memory one ground can take, in bytes: the slots, and in each a mixed brick at its
    /// largest (a palette of 256 Materials and a palette index for each Voxel). The ground of a
    /// walking character is a small part of this: see [`Ground::bytes`].
    pub const MAX_BYTES: usize = SLOTS * (size_of::<Slot>() + MIXED_HEADER + 512 + 512);

    /// A ground that generates from `source`: a store's [`BrickStore::source`].
    pub fn new(source: Option<Arc<dyn BrickSource>>) -> Self {
        Self {
            source,
            slots: vec![None; SLOTS],
            centre: None,
            next: 0,
            rate: RATE,
        }
    }

    /// Generates at most `rate` bricks per [`Ground::fill`] instead of the usual.
    pub fn with_rate(mut self, rate: usize) -> Self {
        self.rate = rate;
        self
    }

    /// New bricks one [`Ground::fill`] generates, at the most.
    pub fn rate(&self) -> usize {
        self.rate
    }

    /// The brick at `coord`, if the ground holds it.
    pub fn get(&self, coord: BrickCoord) -> Option<&Brick> {
        match &self.slots[slot_of(coord)] {
            Some((held, brick)) if *held == coord => Some(brick),
            _ => None,
        }
    }

    /// Bricks held, and the bytes they and the slots take.
    pub fn bytes(&self) -> (usize, usize) {
        let held = self.slots.iter().flatten();
        let storage: usize = held
            .clone()
            .map(|(_, brick)| {
                brick.storage_bytes() + if brick.is_uniform() { 0 } else { MIXED_HEADER }
            })
            .sum();
        (held.count(), self.slots.len() * size_of::<Slot>() + storage)
    }

    /// Starts again around `position`, in Voxels, where a character is put down. Bricks that are
    /// held stay held, for as long as nothing else takes their slots.
    pub fn reset(&mut self, position: [f64; 3]) {
        self.centre = None;
        self.next = 0;
        self.follow(position);
    }

    /// Whether every brick of the ball around the centre is held.
    pub fn is_complete(&self) -> bool {
        self.next == offsets().len()
    }

    /// Moves the ball to be around the character at `position`, if it is [`RECENTRE`] bricks from
    /// the centre and the ball is complete.
    pub fn follow(&mut self, position: [f64; 3]) {
        let brick = brick_of(position);
        match self.centre {
            None => self.centre_on_brick(brick),
            Some(centre) => {
                let far = (0..3).any(|a| centre.0[a].abs_diff(brick.0[a]) > RECENTRE);
                if far && self.is_complete() {
                    self.centre_on_brick(brick);
                }
            }
        }
    }

    /// Moves the ball to be around `leash`'s centre, for a ground that must hold what a leash it
    /// has been told of reaches, and does not.
    pub fn centre_on(&mut self, leash: &Leash) {
        self.centre_on_brick(brick_of(leash.centre));
    }

    fn centre_on_brick(&mut self, brick: BrickCoord) {
        if self.centre != Some(brick) {
            self.centre = Some(brick);
            self.next = 0;
        }
    }

    /// Generates the bricks of the ball that are missing, nearest the centre first, at most
    /// [`Ground::rate`] of them.
    pub fn fill(&mut self) {
        let Some(centre) = self.centre else { return };
        let mut made = 0;
        for offset in &offsets()[self.next..] {
            let coord = beside(centre, offset);
            if self.get(coord).is_none() {
                if made == self.rate {
                    return;
                }
                let brick = self
                    .source
                    .as_ref()
                    .map_or(Brick::AIR, |source| source.brick(0, coord));
                self.slots[slot_of(coord)] = Some((coord, brick));
                made += 1;
            }
            self.next += 1;
        }
    }

    /// The largest ball around the centre that is all held, whole bricks wide (the leash that the
    /// server may hold a character to), if there is one.
    pub fn ready(&self) -> Option<Leash> {
        let centre = self.centre?;
        let radius = match offsets().get(self.next) {
            // The ball is all of the bricks before this one, so it stops short of it.
            Some(first_missing) => i64::from(first_missing.gap2).checked_sub(1)?.isqrt() as i32,
            None => REACH,
        };
        let radius = radius / BRICK_SIZE * BRICK_SIZE;
        (radius > 0).then(|| Leash {
            centre: middle(centre),
            radius: f64::from(radius),
        })
    }

    /// Whether every brick that `leash` reaches is held.
    pub fn covers(&self, leash: &Leash) -> bool {
        if leash.radius.is_nan() || leash.radius > f64::from(REACH) {
            return false;
        }
        let centre = brick_of(leash.centre);
        offsets()
            .iter()
            .take_while(|o| f64::from(o.gap2) <= leash.radius * leash.radius)
            .all(|o| self.get(beside(centre, o)).is_some())
    }
}

/// The Voxels a character collides with: the bricks of the store (the Edits, and what the
/// client or server holds besides) and else the ground's. Nothing else is read, so no query ever
/// generates a brick: a Voxel that neither holds is [`Cell::Unloaded`], which is solid.
pub struct Footing<'a> {
    store: &'a BrickStore,
    ground: &'a Ground,
}

impl<'a> Footing<'a> {
    pub fn new(store: &'a BrickStore, ground: &'a Ground) -> Self {
        Self { store, ground }
    }
}

impl Occupancy for Footing<'_> {
    fn cell(&self, voxel: VoxelCoord) -> Cell {
        let coord = voxel.brick();
        match self.store.brick(coord).or_else(|| self.ground.get(coord)) {
            None => Cell::Unloaded,
            Some(brick) if brick.get(voxel.local()).is_some() => Cell::Solid,
            Some(_) => Cell::Air,
        }
    }
}

#[cfg(test)]
mod tests {
    use std::sync::atomic::{AtomicUsize, Ordering};

    use brick_store::Material;

    use super::*;

    const STONE: Material = Material(7);

    /// Stone below y = 0 and air above, counting the bricks it is asked for.
    #[derive(Debug, Default)]
    struct Counting(AtomicUsize);

    impl BrickSource for Counting {
        fn brick(&self, level: usize, coord: BrickCoord) -> Brick {
            assert_eq!(level, 0);
            self.0.fetch_add(1, Ordering::SeqCst);
            if coord.0[1] < 0 {
                Brick::solid(STONE)
            } else {
                Brick::AIR
            }
        }
    }

    fn counting(rate: usize) -> (Arc<Counting>, Ground) {
        let source = Arc::new(Counting::default());
        let ground = Ground::new(Some(source.clone())).with_rate(rate);
        (source, ground)
    }

    fn made(source: &Counting) -> usize {
        source.0.load(Ordering::SeqCst)
    }

    fn complete(ground: &mut Ground) {
        while !ground.is_complete() {
            ground.fill();
        }
    }

    /// The distance from `point` to the nearest point of `brick`, worked out from the box.
    fn distance_to(brick: BrickCoord, point: [f64; 3]) -> f64 {
        let origin = brick.origin().0;
        (0..3)
            .map(|a| {
                let (lo, hi) = (f64::from(origin[a]), f64::from(origin[a] + BRICK_SIZE));
                let gap = point[a].clamp(lo, hi) - point[a];
                gap * gap
            })
            .sum::<f64>()
            .sqrt()
    }

    #[test]
    fn the_offsets_are_the_bricks_a_ball_touches_nearest_first() {
        let all = offsets();
        assert!(
            all.windows(2)
                .all(|w| (w[0].gap2, w[0].brick) < (w[1].gap2, w[1].brick))
        );
        assert_eq!(all[0].brick, [0, 0, 0]);
        let centre = BrickCoord([0; 3]);
        for x in -12..=12 {
            for y in -12..=12 {
                for z in -12..=12 {
                    let brick = BrickCoord([x, y, z]);
                    let touches = distance_to(brick, middle(centre)) <= f64::from(REACH);
                    let listed = all.iter().any(|o| beside(centre, o) == brick);
                    assert_eq!(listed, touches, "{brick:?}");
                }
            }
        }
    }

    #[test]
    fn every_brick_the_ready_ball_touches_is_held_however_far_the_filling_has_got() {
        let (_, mut ground) = counting(37);
        ground.reset([100.5, 3.0, -40.0]);
        let mut balls = 0;
        while !ground.is_complete() {
            ground.fill();
            let Some(ready) = ground.ready() else {
                continue;
            };
            balls += 1;
            assert!(ground.covers(&ready));
            let centre = brick_of(ready.centre);
            for x in -12..=12 {
                for y in -12..=12 {
                    for z in -12..=12 {
                        let brick = BrickCoord([centre.0[0] + x, centre.0[1] + y, centre.0[2] + z]);
                        if distance_to(brick, ready.centre) <= ready.radius {
                            assert!(ground.get(brick).is_some(), "{brick:?} in {ready:?}");
                        }
                    }
                }
            }
        }
        assert!(balls > 10, "the ready ball grew in {balls} steps");
        assert_eq!(ground.ready().unwrap().radius, f64::from(REACH));
    }

    #[test]
    fn a_fill_generates_at_most_its_rate_and_each_brick_once() {
        let (source, mut ground) = counting(50);
        ground.reset([0.0; 3]);
        ground.fill();
        assert_eq!(made(&source), 50);
        assert!(!ground.is_complete());
        complete(&mut ground);
        assert_eq!(made(&source), offsets().len());
        ground.fill();
        assert_eq!(made(&source), offsets().len());
    }

    #[test]
    fn the_centre_moves_with_the_character_only_when_the_ball_is_complete_and_it_is_far() {
        let (_, mut ground) = counting(1000);
        ground.reset([4.0; 3]);
        let start = ground.centre;
        ground.follow([100.0, 4.0, 4.0]);
        assert_eq!(ground.centre, start, "the ball is not complete");
        complete(&mut ground);
        // 3 bricks away is still near; 4 is not.
        ground.follow([31.0, 4.0, 4.0]);
        assert_eq!(ground.centre, start);
        ground.follow([32.0, 4.0, 4.0]);
        assert_eq!(ground.centre, Some(BrickCoord([4, 0, 0])));
        assert!(!ground.is_complete());
    }

    #[test]
    fn a_ground_walked_far_holds_no_more_than_its_slots_and_has_let_go_of_what_it_left() {
        let (_, mut ground) = counting(1000);
        ground.reset([0.0; 3]);
        let mut x = 0.0;
        for _ in 0..200 {
            complete(&mut ground);
            x += 32.0;
            ground.follow([x, 0.0, 0.0]);
        }
        complete(&mut ground);
        let (held, bytes) = ground.bytes();
        assert!(
            held <= SLOTS && bytes <= Ground::MAX_BYTES,
            "{held} {bytes}"
        );
        assert!(ground.get(BrickCoord([0; 3])).is_none(), "left behind");
        assert!(ground.get(BrickCoord([800, 0, 0])).is_some());
    }

    #[test]
    fn a_collision_query_never_generates_a_brick_and_what_is_not_held_is_solid() {
        let (source, mut ground) = counting(1000);
        ground.reset([0.0; 3]);
        complete(&mut ground);
        let store = BrickStore::new();
        let footing = Footing::new(&store, &ground);
        let before = made(&source);
        // Stone below the ground, air above, and what is far outside the ground not known.
        assert_eq!(footing.cell(VoxelCoord([5, -1, 5])), Cell::Solid);
        assert_eq!(footing.cell(VoxelCoord([5, 0, 5])), Cell::Air);
        assert_eq!(footing.cell(VoxelCoord([5, 70, 5])), Cell::Air);
        assert_eq!(footing.cell(VoxelCoord([5_000, 0, 5])), Cell::Unloaded);
        assert_eq!(footing.cell(VoxelCoord([5, -80_000, 5])), Cell::Unloaded);
        assert_eq!(made(&source), before);
    }

    #[test]
    fn what_the_store_holds_is_read_before_the_ground() {
        let (_, mut ground) = counting(1000);
        ground.reset([0.0; 3]);
        complete(&mut ground);
        let mut store = BrickStore::new();
        // An Edit dug the stone out of the brick below the origin.
        store.insert(BrickCoord([0, -1, 0]), Brick::AIR);
        let footing = Footing::new(&store, &ground);
        assert_eq!(footing.cell(VoxelCoord([5, -1, 5])), Cell::Air);
        assert_eq!(footing.cell(VoxelCoord([5, -9, 5])), Cell::Solid);
    }

    #[test]
    fn a_ground_with_no_source_is_air() {
        let mut ground = Ground::new(None);
        ground.reset([0.0; 3]);
        ground.fill();
        let store = BrickStore::new();
        assert_eq!(
            Footing::new(&store, &ground).cell(VoxelCoord([1, 1, 1])),
            Cell::Air
        );
    }

    #[test]
    fn a_leash_is_covered_only_if_all_its_bricks_are_held() {
        let (_, mut ground) = counting(1000);
        ground.reset([4.0; 3]);
        let wide = Leash {
            centre: [4.0; 3],
            radius: 64.0,
        };
        assert!(!ground.covers(&wide));
        complete(&mut ground);
        assert!(ground.covers(&wide));
        assert!(!ground.covers(&Leash {
            centre: [100.0, 4.0, 4.0],
            radius: 64.0,
        }));
        assert!(!ground.covers(&Leash {
            radius: f64::from(REACH) + 1.0,
            ..wide
        }));
    }
}
